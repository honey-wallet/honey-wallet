// Builds the provider the phone's in-app browser puts in every page (src/worker/phone.ts,
// which brings inpage.ts with it) into one script, saved as a string the app can import:
//
//   pnpm --filter @honey-wallet/extension build:phone   →  src/worker/phone.generated.ts
//
// Run it after changing phone.ts, inpage.ts or protocol.ts; a test fails while it's stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const GENERATED = join(root, 'src/worker/phone.generated.ts');

/** The generated module's text. */
export async function buildPhoneProvider() {
  const icon = `data:image/png;base64,${readFileSync(join(root, 'public/icons/icon-48.png')).toString('base64')}`;
  const result = await build({
    configFile: false,
    logLevel: 'warn',
    define: { __HONEY_ICON__: JSON.stringify(icon) },
    build: {
      write: false,
      minify: true,
      // iOS 15.4 (WKWebView) and Android's System WebView: crypto.randomUUID is the floor.
      target: 'es2020',
      lib: {
        entry: join(root, 'src/worker/phone.ts'),
        formats: ['iife'],
        name: 'honey_phone',
        fileName: () => 'phone.js',
      },
    },
  });
  const [output] = Array.isArray(result) ? result : [result];
  const code = output.output[0].code.trim();
  return `// Generated by scripts/build-phone.mjs from src/worker/phone.ts. Don't edit.\nexport const PHONE_PROVIDER = ${JSON.stringify(code)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(GENERATED, await buildPhoneProvider());
  console.log(`Wrote ${GENERATED}`);
}
